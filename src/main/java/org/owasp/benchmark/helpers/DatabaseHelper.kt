object DatabaseHelper {
    private var conn: Connection? = null
    @JvmStatic
    var JDBCtemplate: JdbcTemplate
    var hibernateUtil: HibernateUtil = HibernateUtil(false)
    var hibernateUtilClassic: HibernateUtil = HibernateUtil(true)
    const val hideSQLErrors: Boolean =
        false // If we want SQL Exceptions to be suppressed from being displayed to the user of

    // the web app.
    init {
        initDataBase()
        hibernateUtil.initData()
        hibernateUtilClassic.initClassicData()

        println("Spring context init() ")
        val ac: ApplicationContext =
            ClassPathXmlApplicationContext(
                "/context.xml", DatabaseHelper::class.java
            )
        val data = ac.getBean("dataSource") as DataSource
        JDBCtemplate = JdbcTemplate(data)
        println("Spring context loaded!")
    }

    fun initDataBase() {
        try {
            executeSQLCommand("DROP PROCEDURE IF EXISTS verifyUserPassword")
            executeSQLCommand("DROP PROCEDURE IF EXISTS verifyEmployeeSalary")
            executeSQLCommand("DROP TABLE IF EXISTS USERS")
            executeSQLCommand("DROP TABLE IF EXISTS EMPLOYEE")
            executeSQLCommand("DROP TABLE IF EXISTS CERTIFICATE")
            executeSQLCommand("DROP TABLE IF EXISTS SCORE")

            executeSQLCommand(
                "CREATE TABLE USERS (userid int NOT NULL GENERATED BY DEFAULT AS IDENTITY, username varchar(50), password varchar(50),PRIMARY KEY (userid));"
            )
            executeSQLCommand(
                "CREATE TABLE SCORE (userid int NOT NULL GENERATED BY DEFAULT AS IDENTITY, nick varchar(50), score INTEGER,PRIMARY KEY (userid));"
            )
            executeSQLCommand(
                "CREATE PROCEDURE verifyUserPassword(IN username_ varchar(50), IN password_ varchar(50))"
                        + " READS SQL DATA"
                        + " DYNAMIC RESULT SETS 1"
                        + " BEGIN ATOMIC"
                        + " DECLARE resultSet SCROLL CURSOR WITH HOLD WITH RETURN FOR SELECT * FROM USERS WHERE USERNAME = username_ AND PASSWORD = password_;"
                        + " OPEN resultSet;"
                        + "END;"
            )

            executeSQLCommand(
                "create table EMPLOYEE ("
                        + "	   id INT NOT NULL GENERATED BY DEFAULT AS IDENTITY,"
                        + "	   first_name VARCHAR(20) default NULL,"
                        + "   last_name  VARCHAR(20) default NULL,"
                        + " salary     INT  default NULL,"
                        + " PRIMARY KEY (id)"
                        + "	);"
            )

            executeSQLCommand(
                "create table CERTIFICATE ("
                        + "	   id INT NOT NULL GENERATED BY DEFAULT AS IDENTITY,"
                        + " certificate_name VARCHAR(30) default NULL,"
                        + " employee_id INT default NULL,"
                        + " PRIMARY KEY (id)"
                        + ");"
            )

            executeSQLCommand(
                "CREATE PROCEDURE verifyEmployeeSalary(IN user_ varchar(50))"
                        + " READS SQL DATA"
                        + " DYNAMIC RESULT SETS 1"
                        + " BEGIN ATOMIC"
                        + " DECLARE resultSet SCROLL CURSOR WITH RETURN FOR SELECT * FROM EMPLOYEE WHERE FIRST_NAME = user_;"
                        + " OPEN resultSet;"
                        + "END;"
            )
            conn!!.commit()
            initData()

            println("DataBase tables/procedures created.")
        } catch (e1: Exception) {
            println(
                "Problem with database table/procedure creations: " + e1.message
            )
        }
    }

    @JvmStatic
    val sqlStatement: Statement?
        get() {
            if (conn == null) {
                sqlConnection
            }
            var stmt: Statement? = null
            try {
                stmt = conn!!.createStatement()
            } catch (e: SQLException) {
                println("Problem with database init.")
            }

            return stmt
        }

    fun reset() {
        initData()
    }

    private fun initData() {
        try {
            executeSQLCommand(
                "INSERT INTO USERS (username, password) VALUES('User01', 'P455w0rd')"
            )
            executeSQLCommand(
                "INSERT INTO USERS (username, password) VALUES('User02', 'B3nchM3rk')"
            )
            executeSQLCommand("INSERT INTO USERS (username, password) VALUES('User03', 'a\$c11')")
            executeSQLCommand("INSERT INTO USERS (username, password) VALUES('foo', 'bar')")

            executeSQLCommand("INSERT INTO SCORE (nick, score) VALUES('User03', 155)")
            executeSQLCommand("INSERT INTO SCORE (nick, score) VALUES('foo', 40)")

            executeSQLCommand(
                "INSERT INTO EMPLOYEE (first_name, last_name, salary) VALUES('foo', 'bar', 34567)"
            )
            conn!!.commit()
        } catch (e1: Exception) {
            println("Problem with database init/reset: " + e1.message)
        }
    }

    @JvmStatic
    val sqlConnection: Connection?
        get() {
            if (conn == null) {
                try {
                    val ctx = InitialContext()
                    val datasource = ctx.lookup("java:comp/env/jdbc/BenchmarkDB") as DataSource
                    conn = datasource.connection
                    conn!!.setAutoCommit(false)
                } catch (e: SQLException) {
                    println("Problem with getSqlConnection.")
                    e.printStackTrace()
                } catch (e: NamingException) {
                    println("Problem with getSqlConnection.")
                    e.printStackTrace()
                }
            }
            return conn
        }

    @Throws(Exception::class)
    fun executeSQLCommand(sql: String?) {
        val stmt = sqlStatement
        stmt!!.executeUpdate(sql)
    }

    @JvmStatic
    @Throws(SQLException::class, IOException::class)
    fun outputUpdateComplete(sql: String?, response: HttpServletResponse) {
        val out = response.writer

        out.write("<!DOCTYPE html>\n<html>\n<body>\n<p>")
        out.write(
            "Update complete for query: "
                    + ESAPI.encoder().encodeForHTML(sql)
                    + "<br>\n"
        )
        out.write("</p>\n</body>\n</html>")
    }

    @Throws(SQLException::class, IOException::class)
    fun outputUpdateComplete(sql: String, resp: MutableList<XMLMessage?>) {
        resp.add(XMLMessage("Update complete for query: $sql\n"))
    }

    @JvmStatic
    @Throws(SQLException::class, IOException::class)
    fun printResults(
        statement: Statement, sql: String?, response: HttpServletResponse
    ) {
        val out = response.writer
        out.write(
            """<!DOCTYPE html PUBLIC "-//W3C//DTD HTML 4.01 Transitional//EN" "http://www.w3.org/TR/html4/loose.dtd">
<html>
<head>
<meta http-equiv="Content-Type" content="text/html; charset=UTF-8">
</head>
<body>
<p>
"""
        )

        try {
            val rs = statement.resultSet
            if (rs == null) {
                out.write(
                    "Results set is empty for query: "
                            + ESAPI.encoder().encodeForHTML(sql)
                )
                return
            }

            val rsmd = rs.metaData
            val numberOfColumns = rsmd.columnCount
            out.write("Your results are:<br>\n")

            while (rs.next()) {
                for (i in 1..numberOfColumns) {
                    if (i > 1) {
                        out.write(",  ")
                    }
                    val columnValue = rs.getString(i)
                    out.write(ESAPI.encoder().encodeForHTML(columnValue))
                }
                out.write("<br>\n")
            }
        } finally {
            out.write("</p>\n</body>\n</html>")
        }
    }

    /**
     * Used by the Web Services XML in/out test cases.
     *
     * @param statement
     * @param sql
     * @param resp
     * @throws java.sql.SQLException
     * @throws IOException
     */
    @JvmStatic
    @Throws(SQLException::class, IOException::class)
    fun printResults(statement: Statement, sql: String, resp: MutableList<XMLMessage?>) {
        val rs = statement.resultSet
        if (rs == null) {
            resp.add(XMLMessage("Results set is empty for query: $sql\n"))
            return
        }
        val rsmd = rs.metaData
        val numberOfColumns = rsmd.columnCount
        resp.add(XMLMessage("Your results are:\n"))
        while (rs.next()) {
            for (i in 1..numberOfColumns) {
                val columnValue = rs.getString(i)
                if (i == 0) {
                    resp.add(XMLMessage(columnValue))
                } else resp.add(XMLMessage(",  $columnValue"))
            }
            resp.add(XMLMessage("\n"))
        }
    }

