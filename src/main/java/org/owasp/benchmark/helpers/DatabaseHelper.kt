                val columnValue = rs.getString(i)
                resp.add(XMLMessage(columnValue))
            }
            resp.add(XMLMessage("\n"))
        }
    }

    @JvmStatic
    @Throws(IOException::class)
    fun printResults(query: String?, counts: IntArray, response: HttpServletResponse) {
        val out = response.writer
        out.write("<!DOCTYPE html>\n<html>\n<body>\n<p>")
        out.write("For query: " + ESAPI.encoder().encodeForHTML(query) + "<br>")
        try {
            if (counts.size > 0) {
                if (counts[0] == Statement.SUCCESS_NO_INFO) {
                    out.write(
                        "The SQL query was processed successfully but the number of rows affected is unknown."
                    )
                } else if (counts[0] == Statement.EXECUTE_FAILED) {
                    out.write(
                        "The SQL query failed to execute successfully and occurs only if a driver continues to process commands after a command fails"
                    )
                } else {
                    out.write("The number of affected rows are: " + counts[0])
                }
            }
        } finally {
            out.write("</p>\n</body>\n</html>")
        }
    }

    @Throws(IOException::class)
    fun printResults(query: String?, counts: IntArray, resp: MutableList<XMLMessage?>) {
        resp.add(XMLMessage("For query:\n"))

        if (counts.size > 0) {
            if (counts[0] == Statement.SUCCESS_NO_INFO) {
                resp.add(
                    XMLMessage(
                        "The SQL query was processed successfully but the number of rows affected is unknown."
                    )
                )
            } else if (counts[0] == Statement.EXECUTE_FAILED) {
                resp.add(
                    XMLMessage(
                        "The SQL query failed to execute successfully and occurs only if a driver continues to process commands after a command fails"
                    )
                )
            } else {
                resp.add(XMLMessage("The number of affected rows are: " + counts[0]))
            }
        }
    }

    @Throws(SQLException::class)
    fun printColTypes(rsmd: ResultSetMetaData, out: PrintWriter) {
        val columns = rsmd.columnCount
        for (i in 1..columns) {
            val jdbcType = rsmd.getColumnType(i)
            val name = rsmd.getColumnTypeName(i)
            out.write(
                "Column "
                        + i
                        + " is JDBC type "
                        + jdbcType
                        + ", which the DBMS calls "
                        + name
                        + "<br>\n"
            )
        }
    }
}
