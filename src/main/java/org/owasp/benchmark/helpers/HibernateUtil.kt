    var classicSession: org.hibernate.classic.Session? = null
    var st: Statement? = null
    var sessionFactory: SessionFactory
    var serviceRegistry: ServiceRegistry? = null
    var conn: Connection? = null

    init {
        Logger.getLogger("org.hibernate").level = Level.OFF
        val configuration = Configuration()

        configuration.configure("hibernate.cfg.xml")

        /* HB4 Conf
         * serviceRegistry = new StandardServiceRegistryBuilder().applySettings(
         * configuration.getProperties()).build(); sessionFactory =
         * configuration.buildSessionFactory(serviceRegistry);
         */
        sessionFactory = configuration.buildSessionFactory()

        // TODO: Decide if we want to support both Hibernate 2 AND Hibernate 3 test cases. If not,
        // then dump the classicSession stuff
        // And any test cases against deprecated APIs from Hibernate 2.
        if (classic) {
            classicSession = sessionFactory.openSession()
        } else {
            session = sessionFactory.openSession()
        }

        try {
            Class.forName("org.hsqldb.jdbcDriver")
            //			System.out.println("Driver Loaded.");
            val url = "jdbc:hsqldb:benchmarkDataBase;sql.enforce_size=false"
            conn = DriverManager.getConnection(url, "sa", "")
            //			System.out.println("Got Connection.");
            st = conn!!.createStatement()
        } catch (e: SQLException) {
            println("Problem with hibernate init.")
        } catch (e: ClassNotFoundException) {
            println("Problem with hibernate init.")
        }
    }

    fun destroySession() {
        session!!.close()
        if (conn != null) try {
            conn!!.close()
        } catch (e: SQLException) {
            println("Problem with hibernate closing connection.")
        }

        // HB4 conf
        // StandardServiceRegistryBuilder.destroy(serviceRegistry);
    }

    fun destroyClassicSession() {
        classicSession!!.close()
        if (conn != null) try {
            conn!!.close()
        } catch (e: SQLException) {
            println("Problem with hibernate closing connection.")
        }
    }

    @Throws(Exception::class)
    fun executeSQLCommand(sql: String?) {
        st!!.executeUpdate(sql)
    }

