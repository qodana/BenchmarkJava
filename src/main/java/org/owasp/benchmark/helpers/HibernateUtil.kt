    @Throws(Exception::class)
    fun checkData(sql: String?) {
        val query = session!!.createQuery(sql)
        val list: MutableList<User?> = ArrayList()
        for (o in query.list()) {
            list.add(o as User?)
        }

        for (user in list) {
            println(user!!.userId)
            println(user.name)
            println(user.password)
        }
    }

