import org.springframework.dao.DataAccessException
import java.io.IOException
import javax.servlet.ServletException
import javax.servlet.annotation.WebServlet
import javax.servlet.http.HttpServlet
import javax.servlet.http.HttpServletRequest
import javax.servlet.http.HttpServletResponse

@WebServlet(value = ["/sqli-01/BenchmarkTest00769"])
class BenchmarkTest00769 : HttpServlet() {
    @Throws(ServletException::class, IOException::class)
    public override fun doGet(request: HttpServletRequest, response: HttpServletResponse) {
        doPost(request, response)
    }

    @Throws(ServletException::class, IOException::class)
    public override fun doPost(request: HttpServletRequest, response: HttpServletResponse) {
        response.contentType = "text/html;charset=UTF-8"

        val values = request.getParameterValues("BenchmarkTest00769")
        val param = if (values != null && values.size > 0) values[0]
        else ""

        var bar: String? = "safe!"
        val map29572 = HashMap<String, Any>()
        map29572["keyA-29572"] = "a-Value" // put some stuff in the collection
        map29572["keyB-29572"] = param // put it in a collection
        map29572["keyC"] = "another-Value" // put some stuff in the collection
        bar = map29572["keyB-29572"] as String? // get it back out

        try {
            val sql = "SELECT * from USERS where USERNAME='foo' and PASSWORD='$bar'"

            DatabaseHelper.JDBCtemplate.batchUpdate(sql)
            response.writer
                .println(
                    "No results can be displayed for query: "
                            + ESAPI.encoder().encodeForHTML(sql)
                            + "<br>"
                            + " because the Spring batchUpdate method doesn't return results."
                )
        } catch (e: DataAccessException) {
            if (DatabaseHelper.hideSQLErrors) {
                response.writer.println("Error processing request.")
            } else throw ServletException(e)
        }
    }

    companion object {
        private const val serialVersionUID = 1L
    }
}
