package org.owasp.benchmark.testcode

import org.apache.commons.codec.binary.Base64
import org.owasp.benchmark.helpers.ThingFactory
import org.owasp.esapi.ESAPI
import java.io.File
import java.io.IOException
import java.net.URLDecoder
import javax.servlet.ServletException
import javax.servlet.annotation.WebServlet
import javax.servlet.http.HttpServlet
import javax.servlet.http.HttpServletRequest
import javax.servlet.http.HttpServletResponse



@WebServlet(value = ["/pathtraver-01/BenchmarkTest01026"])
class BenchmarkTest01026 : HttpServlet() {
    @Throws(ServletException::class, IOException::class)
    public override fun doGet(request: HttpServletRequest, response: HttpServletResponse) {
        doPost(request, response)
    }

    @Throws(ServletException::class, IOException::class)
    public override fun doPost(request: HttpServletRequest, response: HttpServletResponse) {
        response.contentType = "text/html;charset=UTF-8"

        var param = ""
        if (request.getHeader("BenchmarkTest01026") != null) {
            param = request.getHeader("BenchmarkTest01026")
        }

        // URL Decode the header value since req.getHeader() doesn't. Unlike req.getParameter().
        param = URLDecoder.decode(param, "UTF-8")

        val bar = Test().doSomething(request, param)

        val fileTarget = File(bar)
        response.writer
            .println(
                "Access to file: '"
                        + ESAPI
                    .encoder()
                    .encodeForHTML(fileTarget.toString())
                        + "' created."
            )
        if (fileTarget.exists()) {
            response.writer.println(" And file already exists.")
        } else {
            response.writer.println(" But file doesn't exist yet.")
        }
    } // end doPost

    private inner class Test {
        @Throws(ServletException::class, IOException::class)
        fun doSomething(request: HttpServletRequest?, param: String): String? {
            // Chain a bunch of propagators in sequence

            val a11433 = param // assign
            val b11433 = StringBuilder(a11433) // stick in stringbuilder
            b11433.append(" SafeStuff") // append some safe content
            b11433.replace(
                b11433.length - "Chars".length,
                b11433.length,
                "Chars"
            ) // replace some of the end content
            val map11433 = HashMap<String, Any>()
            map11433["key11433"] = b11433.toString() // put in a collection
            val c11433 = map11433["key11433"] as String? // get it back out
            val d11433 = c11433!!.substring(0, c11433.length - 1) // extract most of it
            val e11433 = String(
                Base64.decodeBase64(
                    Base64.encodeBase64(
                        d11433.toByteArray()
                    )
                )
            ) // B64 encode and decode it
            val f11433 =
                e11433.split(" ".toRegex()).dropLastWhile { it.isEmpty() }.toTypedArray()[0] // split it on a space
            val thing =
                ThingFactory.createThing()
            val g11433 = "barbarians_at_the_gate" // This is static so this whole flow is 'safe'
            val bar = thing.doSomething(g11433) // reflection

            return bar
        }
    } // end innerclass Test

    companion object {
        private const val serialVersionUID = 1L
    }
} // end DataflowThruInnerClass

