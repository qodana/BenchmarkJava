@WebServlet(value = ["/xss-05/BenchmarkTest02587"])
class BenchmarkTest02587 : HttpServlet() {
    @Throws(ServletException::class, IOException::class)
    public override fun doGet(request: HttpServletRequest, response: HttpServletResponse) {
        doPost(request, response)
    }

    @Throws(ServletException::class, IOException::class)
    public override fun doPost(request: HttpServletRequest, response: HttpServletResponse) {
        response.contentType = "text/html;charset=UTF-8"

        val queryString = request.queryString
        val paramval = "BenchmarkTest02587" + "="
        var paramLoc = -1
        if (queryString != null) paramLoc = queryString.indexOf(paramval)
        if (paramLoc == -1) {
            response.writer
                .println(
                    "getQueryString() couldn't find expected parameter '"
                            + "BenchmarkTest02587"
                            + "' in query string."
                )
            return
        }

        var param: String? =
            queryString!!.substring(
                paramLoc
                        + paramval
                    .length
            ) // 1st assume "BenchmarkTest02587" param is last
        // parameter in query string.
        // And then check to see if its in the middle of the query string and if so, trim off what
        // comes after.
        val ampersandLoc = queryString.indexOf("&", paramLoc)
        if (ampersandLoc != -1) {
            param = queryString.substring(paramLoc + paramval.length, ampersandLoc)
        }
        param = URLDecoder.decode(param, "UTF-8")

        val bar = doSomething(request, param)

        response.setHeader("X-XSS-Protection", "0")
        val obj = arrayOf("a", bar)
        response.writer.printf(Locale.US, "Formatted like: %1\$s and %2\$s.", *obj)
    } // end doPost

    companion object {
        private const val serialVersionUID = 1L

        @Throws(ServletException::class, IOException::class)
        private fun doSomething(request: HttpServletRequest, param: String): String? {
            // Chain a bunch of propagators in sequence

            val a93081 = param // assign
            val b93081 = StringBuilder(a93081) // stick in stringbuilder
            b93081.append(" SafeStuff") // append some safe content
            b93081.replace(
                b93081.length - "Chars".length,
                b93081.length,
                "Chars"
            ) // replace some of the end content
            val map93081 = HashMap<String, Any>()
            map93081["key93081"] = b93081.toString() // put in a collection
            val c93081 = map93081["key93081"] as String? // get it back out
            val d93081 = c93081!!.substring(0, c93081.length - 1) // extract most of it
            val e93081 = String(
                Base64.decodeBase64(
                    Base64.encodeBase64(
                        d93081.toByteArray()
                    )
                )
            ) // B64 encode and decode it
            val f93081 =
                e93081.split(" ".toRegex()).dropLastWhile { it.isEmpty() }.toTypedArray()[0] // split it on a space
            val thing =
                ThingFactory.createThing()
            val bar = thing.doSomething(f93081) // reflection

            return bar
        }
    }
}
