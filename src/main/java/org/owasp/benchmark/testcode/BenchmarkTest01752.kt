package org.owasp.benchmark.testcode

import org.owasp.benchmark.helpers.*
import org.owasp.esapi.ESAPI
import java.io.FileInputStream
import java.io.FileOutputStream
import java.io.IOException
import javax.servlet.ServletException
import javax.servlet.annotation.WebServlet
import javax.servlet.http.HttpServlet
import javax.servlet.http.HttpServletRequest
import javax.servlet.http.HttpServletResponse



@WebServlet(value = ["/pathtraver-02/BenchmarkTest01752"])
class BenchmarkTest01752 : HttpServlet() {
    @Throws(ServletException::class, IOException::class)
    public override fun doGet(request: HttpServletRequest, response: HttpServletResponse) {
        doPost(request, response)
    }

    @Throws(ServletException::class, IOException::class)
    public override fun doPost(request: HttpServletRequest, response: HttpServletResponse) {
        response.contentType = "text/html;charset=UTF-8"

        val scr =
            SeparateClassRequest(request)
        val param = scr.getTheValue("BenchmarkTest01752")

        val bar = Test().doSomething(request, param)

        val fileName = Utils.TESTFILES_DIR + bar

        try {
            FileOutputStream(FileInputStream(fileName).fd).use { fos ->
                response.writer
                    .println(
                        "Now ready to write to file: "
                                + ESAPI.encoder().encodeForHTML(fileName)
                    )
            }
        } catch (e: Exception) {
            println("Couldn't open FileOutputStream on file: '$fileName'")
        }
    } // end doPost

    private inner class Test {
        @Throws(ServletException::class, IOException::class)
        fun doSomething(request: HttpServletRequest?, param: String): String? {
            var bar: String? = "safe!"
            val map11351 = HashMap<String, Any>()
            map11351["keyA-11351"] = "a-Value" // put some stuff in the collection
            map11351["keyB-11351"] = param // put it in a collection
            map11351["keyC"] = "another-Value" // put some stuff in the collection
            bar = map11351["keyB-11351"] as String? // get it back out

            return bar
        }
    } // end innerclass Test

    companion object {
        private const val serialVersionUID = 1L
    }
} // end DataflowThruInnerClass

